-- ---------------------------------------------------------------- dim_exploitation (SCD2)
CREATE TABLE IF NOT EXISTS dwh.dim_exploitation (
    exploitation_sk   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_exploitation   TEXT NOT NULL,             -- clé naturelle
    nom_exploitation  TEXT,
    systeme_elevage   TEXT,                      -- Transhumant, Pastoral, Sédentaire...
    classe_taille     TEXT,                      -- attribut suivi (SCD2)
    proprietaire      TEXT,                      -- attribut suivi (SCD2)
    region            TEXT,                      -- attribut suivi (SCD2)
    pcode_zone        TEXT,                      -- attribut suivi (SCD2)
    statut_sanitaire  TEXT,                      -- attribut suivi (SCD2)
    date_debut        DATE NOT NULL,
    date_fin          DATE NOT NULL DEFAULT DATE '9999-12-31',
    est_courant       BOOLEAN NOT NULL DEFAULT TRUE,
    hash_diff         CHAR(32) NOT NULL,         -- md5 des attributs suivis
    batch_id          BIGINT,
    CHECK (date_fin >= date_debut)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_dim_exploitation_courant
    ON dwh.dim_exploitation (id_exploitation) WHERE est_courant;
CREATE INDEX IF NOT EXISTS ix_dim_exploitation_nk
    ON dwh.dim_exploitation (id_exploitation, date_debut);
INSERT INTO dwh.dim_exploitation (exploitation_sk, id_exploitation, nom_exploitation, date_debut, hash_diff)
VALUES (-1, 'INCONNU', 'Inconnue', DATE '1900-01-01', repeat('0', 32)) ON CONFLICT DO NOTHING;

-- ---------------------------------------------------------------- dim_veterinaire (SCD2)
CREATE TABLE IF NOT EXISTS dwh.dim_veterinaire (
    veterinaire_sk    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_veterinaire    TEXT NOT NULL,
    nom               TEXT,
    prenom            TEXT,
    statut            TEXT,                      -- public / privé (SCD2)
    specialite        TEXT,
    pcode_departement TEXT,                      -- zone d'exercice (SCD2)
    date_prise_poste  DATE,
    date_debut        DATE NOT NULL,
    date_fin          DATE NOT NULL DEFAULT DATE '9999-12-31',
    est_courant       BOOLEAN NOT NULL DEFAULT TRUE,
    hash_diff         CHAR(32) NOT NULL,
    batch_id          BIGINT,
    CHECK (date_fin >= date_debut)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_dim_veterinaire_courant
    ON dwh.dim_veterinaire (id_veterinaire) WHERE est_courant;
