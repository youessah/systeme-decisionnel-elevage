-- 03_dimensions.sql : dimensions conformes. SCD2 sur dim_exploitation et dim_veterinaire.
-- Chaque dimension contient un membre « inconnu » (sk = -1).

-- ---------------------------------------------------------------- dim_date
CREATE TABLE IF NOT EXISTS dwh.dim_date (
    date_sk        INT PRIMARY KEY,              -- AAAAMMJJ
    date_jour      DATE NOT NULL UNIQUE,
    annee          SMALLINT NOT NULL,
    trimestre      SMALLINT NOT NULL,
    mois           SMALLINT NOT NULL,
    nom_mois       TEXT NOT NULL,
    semaine_iso    SMALLINT NOT NULL,
    jour_semaine   SMALLINT NOT NULL,            -- 1 = lundi
    nom_jour       TEXT NOT NULL,
    saison         TEXT NOT NULL,                -- 'sèche' (nov-mars) ou 'pluies' (avr-oct)
    est_weekend    BOOLEAN NOT NULL,
    est_ferie      BOOLEAN NOT NULL DEFAULT FALSE,
    nom_ferie      TEXT
);

INSERT INTO dwh.dim_date
SELECT to_char(d, 'YYYYMMDD')::INT, d::DATE,
       EXTRACT(YEAR FROM d), EXTRACT(QUARTER FROM d), EXTRACT(MONTH FROM d),
       (ARRAY['janvier','février','mars','avril','mai','juin','juillet','août','septembre','octobre','novembre','décembre'])[EXTRACT(MONTH FROM d)::INT],
       EXTRACT(WEEK FROM d), EXTRACT(ISODOW FROM d),
       (ARRAY['lundi','mardi','mercredi','jeudi','vendredi','samedi','dimanche'])[EXTRACT(ISODOW FROM d)::INT],
       CASE WHEN EXTRACT(MONTH FROM d) IN (11,12,1,2,3) THEN 'sèche' ELSE 'pluies' END,
       EXTRACT(ISODOW FROM d) IN (6,7), FALSE, NULL
FROM generate_series('2020-01-01'::DATE, '2030-12-31'::DATE, INTERVAL '1 day') AS d
ON CONFLICT (date_sk) DO NOTHING;

-- Jours fériés à date fixe (Cameroun) ; les fêtes mobiles sont chargées par l'ETL
UPDATE dwh.dim_date SET est_ferie = TRUE,
  nom_ferie = CASE to_char(date_jour, 'MM-DD')
      WHEN '01-01' THEN 'Jour de l''an'      WHEN '02-11' THEN 'Fête de la jeunesse'
      WHEN '05-01' THEN 'Fête du travail'    WHEN '05-20' THEN 'Fête nationale'
      WHEN '08-15' THEN 'Assomption'         WHEN '12-25' THEN 'Noël' END
WHERE to_char(date_jour, 'MM-DD') IN ('01-01','02-11','05-01','05-20','08-15','12-25');

