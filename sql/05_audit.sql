-- 05_audit.sql : journalisation, rejets, filigranes (incrémental), événements (déclencheur base)

-- Un lot (batch) = une exécution de l'ETL
CREATE SEQUENCE IF NOT EXISTS audit.seq_batch_id START 1;

CREATE TABLE IF NOT EXISTS audit.etl_run_log (
    run_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id         BIGINT NOT NULL,
    nom_job          TEXT NOT NULL,
    source           TEXT NOT NULL,
    declencheur      TEXT,                          -- planification / depot_fichier / trigger_base / manuel
    mode_chargement  TEXT,                          -- complet / incremental
    debut            TIMESTAMP NOT NULL DEFAULT now(),
    fin              TIMESTAMP,
    statut           TEXT NOT NULL DEFAULT 'EN_COURS' CHECK (statut IN ('EN_COURS','SUCCES','ECHEC','PARTIEL')),
    lignes_lues      BIGINT DEFAULT 0,
    lignes_chargees  BIGINT DEFAULT 0,
    lignes_rejetees  BIGINT DEFAULT 0,
    message_erreur   TEXT
);
CREATE INDEX IF NOT EXISTS ix_runlog_batch ON audit.etl_run_log (batch_id, source);

CREATE TABLE IF NOT EXISTS audit.etl_reject (
    reject_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id         BIGINT NOT NULL,
    source           TEXT NOT NULL,
    cle_naturelle    TEXT,
    code_motif       TEXT NOT NULL,                 -- DOUBLON, MANQUANT, TYPE, PLAGE, REF_INCONNUE, COHERENCE, UNITE
    detail_motif     TEXT,
    ligne_brute      JSONB NOT NULL,
    horodatage       TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_reject_batch ON audit.etl_reject (batch_id, code_motif);

-- Filigrane : mis à jour uniquement après un chargement réussi (reprise sur incident)
CREATE TABLE IF NOT EXISTS audit.etl_watermark (
    source           TEXT PRIMARY KEY,
    type_filigrane   TEXT NOT NULL,                 -- updated_at / date / id / hash_fichier
    valeur           TEXT,
    batch_id         BIGINT,
    maj_le           TIMESTAMP NOT NULL DEFAULT now()
);

-- Événements capturés par trigger dans la base source, consommés par l'ETL
CREATE TABLE IF NOT EXISTS audit.etl_event (
    event_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_source     TEXT NOT NULL,
    operation        TEXT NOT NULL CHECK (operation IN ('INSERT','UPDATE','DELETE')),
    cle              JSONB,
    cree_le          TIMESTAMP NOT NULL DEFAULT now(),
    traite           BOOLEAN NOT NULL DEFAULT FALSE,
    traite_le        TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_event_a_traiter ON audit.etl_event (traite) WHERE NOT traite;

-- Fonction générique à brancher sur les tables sources (voir script de démonstration) :
--   CREATE TRIGGER trg_audit AFTER INSERT OR UPDATE OR DELETE ON <table_source>
--   FOR EACH ROW EXECUTE FUNCTION audit.fn_capture_event('<colonne_cle>');
CREATE OR REPLACE FUNCTION audit.fn_capture_event() RETURNS trigger AS $$
DECLARE
    col_cle TEXT := TG_ARGV[0];
    ligne   JSONB := to_jsonb(CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END);
BEGIN
    INSERT INTO audit.etl_event (table_source, operation, cle)
    VALUES (TG_TABLE_NAME, TG_OP, jsonb_build_object(col_cle, ligne -> col_cle));
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;
